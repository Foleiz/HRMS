-- สัญญาจ้างแนบไฟล์ได้หลายไฟล์ (Contract multi-file attachments)
create table if not exists hrms.employment_contract_document (
  id            bigint generated by default as identity primary key,
  contract_id   bigint not null references hrms.employment_contract(id) on delete cascade,
  file_name     varchar(255) not null,
  mime_type     varchar(100),
  file_size     bigint,
  file_data     bytea not null,
  uploaded_at   timestamptz not null default now()
);
create index if not exists ix_employment_contract_document_contract
  on hrms.employment_contract_document (contract_id);

-- ย้ายไฟล์เดิม (คอลัมน์ document_* บน employment_contract) มาเป็นแถวแรกของตารางใหม่
insert into hrms.employment_contract_document (contract_id, file_name, mime_type, file_size, file_data, uploaded_at)
select c.id,
       coalesce(nullif(c.document_file_name, ''), 'contract'),
       c.document_mime_type,
       coalesce(c.document_file_size, length(c.document_file_data)),
       c.document_file_data,
       coalesce(c.document_uploaded_at, now())
from hrms.employment_contract c
where c.document_file_data is not null
  and not exists (select 1 from hrms.employment_contract_document d where d.contract_id = c.id);
