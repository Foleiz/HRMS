-- ==============================================================================
-- ตารางข้อมูลหลัก "เพศ" (hrms.gender_type) สำหรับแท็บ เพศ ในเมนู ข้อมูลหลัก
-- รันซ้ำได้ — ไม่ทับข้อมูลเดิม
-- id 1/2/3 ตรงกับที่ระบบใช้อยู่ (ชาย / หญิง / ไม่ระบุ)
-- ==============================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS hrms.gender_type (
    id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gender_code varchar(20) NOT NULL UNIQUE,
    gender_name varchar(50) NOT NULL
);

INSERT INTO hrms.gender_type (id, gender_code, gender_name) VALUES
    (1, 'M', 'ชาย'),
    (2, 'F', 'หญิง'),
    (3, 'O', 'ไม่ระบุ')
ON CONFLICT DO NOTHING;

-- ขยับ sequence ให้ต่อจาก id ล่าสุด (กันชน id ตอนเพิ่มเพศใหม่จากหน้าจอ)
SELECT setval(pg_get_serial_sequence('hrms.gender_type', 'id'),
              GREATEST((SELECT COALESCE(MAX(id), 0) FROM hrms.gender_type), 1));

COMMIT;
