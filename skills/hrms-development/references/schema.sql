-- Compensation & Payroll
CREATE TABLE hrms.salary_structure (
	id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	position_id int8 NULL REFERENCES hrms."position"(id),
	level_id int8 NULL REFERENCES hrms.employee_level(id),
	min_salary numeric(15, 2) DEFAULT 0 NOT NULL CHECK (min_salary >= 0),
	max_salary numeric(15, 2) DEFAULT 0 NOT NULL,
	default_salary numeric(15, 2) NULL,
	effective_from date NOT NULL,
	effective_to date NULL,
	CHECK (max_salary >= min_salary),
	CHECK (default_salary IS NULL OR (default_salary >= min_salary AND default_salary <= max_salary)),
	CHECK (effective_to IS NULL OR effective_to >= effective_from),
	CHECK (position_id IS NOT NULL OR level_id IS NOT NULL)
);

CREATE TABLE hrms.employee_salary (
	id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	employee_id int8 NOT NULL REFERENCES hrms.employee(id),
	base_salary numeric(15, 2) NOT NULL CHECK (base_salary >= 0),
	effective_from date NOT NULL,
	effective_to date NULL,
	reason text NULL,
	approved_by_employee_id int8 NULL REFERENCES hrms.employee(id),
	created_at timestamptz DEFAULT now() NOT NULL,
	CHECK (effective_to IS NULL OR effective_to >= effective_from)
);

CREATE TABLE hrms.payroll_item (
	id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	item_code varchar(50) NOT NULL UNIQUE,
	item_name varchar(255) NOT NULL,
	item_type varchar(20) NOT NULL CHECK (item_type IN ('EARNING', 'DEDUCTION')),
	calculation_type varchar(30) NOT NULL CHECK (calculation_type IN ('FIXED', 'FORMULA', 'MANUAL', 'IMPORT')),
	taxable bool DEFAULT false NOT NULL,
	social_security bool DEFAULT false NOT NULL,
	status varchar(20) DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE hrms.tax_bracket (
	id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	bracket_name varchar(100) NOT NULL,
	income_from numeric(15, 2) NOT NULL,
	income_to numeric(15, 2) NULL,
	tax_rate numeric(5, 2) NOT NULL CHECK (tax_rate >= 0 AND tax_rate <= 100),
	base_tax_amount numeric(15, 2) DEFAULT 0 NOT NULL,
	effective_from date NOT NULL,
	effective_to date NULL,
	status varchar(20) DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE')),
	CHECK (income_to IS NULL OR income_to > income_from),
	CHECK (effective_to IS NULL OR effective_to >= effective_from)
