	employer_rate numeric(5, 2) NOT NULL CHECK (employer_rate >= 0 AND employer_rate <= 100),
	min_wage_base numeric(15, 2) DEFAULT 0 NOT NULL,
	max_wage_base numeric(15, 2) NOT NULL,
	effective_from date NOT NULL,
	effective_to date NULL,
	status varchar(20) DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE')),
	CHECK (max_wage_base >= min_wage_base),
	CHECK (effective_to IS NULL OR effective_to >= effective_from)
);

